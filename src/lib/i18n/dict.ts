export function translate(lang: LangCode, key: DictKey, vars?: Record<string, string | number>) {
  let s: string = dictionaries[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
