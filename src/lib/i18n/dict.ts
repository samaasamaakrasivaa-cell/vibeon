export const dictionaries: Record<LangCode, Record<DictKey, string>> = { ru, en };

export function translate(lang: LangCode, key: DictKey, vars?: Record<string, string | number>) {
  let s: string = dictionaries[lang][key] ?? key;
  if (vars) {
    // склонение после числа: {n:урок|урока|уроков} (ru) / {n:lesson|lessons} (en)
    s = s.replace(/\{(\w+):([^}]+)\}/g, (m, k: string, forms: string) => (k in vars ? pluralForm(lang, Number(vars[k]), forms.split("|")) : m));
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function pluralForm(lang: LangCode, n: number, f: string[]) {
  const a = Math.abs(Math.trunc(n));
  if (lang === "en" || f.length < 3) return a === 1 ? f[0] : (f[1] ?? f[0]);
  const d = a % 10, h = a % 100;
  return d === 1 && h !== 11 ? f[0] : d >= 2 && d <= 4 && (h < 12 || h > 14) ? f[1] : f[2];
}
